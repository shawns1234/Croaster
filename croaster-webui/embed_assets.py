"""Embed the web UI (web/) in the firmware as gzipped byte arrays.

Writes src/webui_assets.h. Runs as the library's PlatformIO extra script
(library.json "build.extraScript") before every build, and from a shell:

    python3 embed_assets.py          # regenerate when web/ changed
    python3 embed_assets.py --check  # exit 1 when src/webui_assets.h is out of date

The header records a SHA-256 of the sources and is only rewritten when that
changes, so builds on machines with a different zlib do not touch a committed,
up-to-date header. Gzip output is deterministic for one zlib: mtime 0, no file
name, level 9. Each asset's ETag is a hash of its gzipped bytes. Sources are
read with CRLF folded to LF, so the result does not depend on the checkout's
line endings.
"""

import gzip
import hashlib
import os
import sys

MIME = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".svg": "image/svg+xml",
    ".json": "application/json",
}
BUDGET_BYTES = 100 * 1024  # total gzipped size allowed for the page
HASH_TAG = "// Source SHA-256: "
FORMAT = b"webui_assets v1"  # bump when render() changes, so committed headers regenerate


def lib_dir():
    try:
        return os.path.dirname(os.path.abspath(__file__))
    except NameError:  # SCons runs extra scripts without __file__
        return Dir(".").srcnode().abspath  # noqa: F821 (SCons builtin)


def sources(web):
    # CRLF is folded to LF so a Windows checkout embeds and hashes the same
    # bytes as the committed header (all page sources are text).
    names = sorted(n for n in os.listdir(web) if os.path.splitext(n)[1] in MIME)
    return [(n, open(os.path.join(web, n), "rb").read().replace(b"\r\n", b"\n")) for n in names]


def source_hash(files):
    h = hashlib.sha256(FORMAT + b"\0")
    for name, data in files:
        h.update(name.encode() + b"\0" + data + b"\0")
    return h.hexdigest()


def gz(data):
    return gzip.compress(data, compresslevel=9, mtime=0)


def ident(name):
    return "k" + "".join(c if c.isalnum() else "_" for c in name)


def render(files, digest):
    out = [
        "#pragma once",
        "// Generated by croaster-webui/embed_assets.py from croaster-webui/web/. Do not edit:",
        "// change the sources in web/ and build (or run the script).",
        HASH_TAG + digest,
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace webui {",
        "",
        "struct Asset {",
        "    const char* path;    // URI served",
        "    const char* type;    // Content-Type",
        "    const uint8_t* data; // gzipped body",
        "    size_t size;",
        "    const char* etag;",
        "};",
        "",
    ]
    entries = []
    total = 0
    for name, data in files:
        body = gz(data)
        total += len(body)
        etag = hashlib.sha256(body).hexdigest()[:16]
        out.append("// %s: %d bytes, %d gzipped" % (name, len(data), len(body)))
        out.append("static const uint8_t %s[] = {" % ident(name))
        for i in range(0, len(body), 16):
            out.append("    " + ", ".join("0x%02x" % b for b in body[i:i + 16]) + ",")
        out.append("};")
        out.append("")
        mime = MIME[os.path.splitext(name)[1]]
        paths = ["/" + name] + (["/"] if name == "index.html" else [])
        for p in paths:
            entries.append('    {"%s", "%s", %s, sizeof(%s), %s},' %
                           (p, mime, ident(name), ident(name), '"\\"%s\\""' % etag))
    out.append("static const Asset kAssets[] = {")
    out.extend(entries)
    out.append("};")
    out.append("static constexpr size_t kAssetCount = sizeof(kAssets) / sizeof(kAssets[0]);")
    out.append("static constexpr size_t kGzippedBytes = %d;" % total)
    out.append("")
    out.append("} // namespace webui")
    out.append("")
    return "\n".join(out), total


def current_hash(path):
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith(HASH_TAG):
                return line[len(HASH_TAG):].strip()
    return None


def run(check=False):
    root = lib_dir()
    web = os.path.join(root, "web")
    out = os.path.join(root, "src", "webui_assets.h")
    files = sources(web)
    digest = source_hash(files)
    if current_hash(out) == digest:
        return 0
    if check:
        print("croaster-webui: src/webui_assets.h is out of date; run embed_assets.py")
        return 1
    text, total = render(files, digest)
    if total > BUDGET_BYTES:
        print("croaster-webui: page is %d bytes gzipped, over the %d byte budget" % (total, BUDGET_BYTES))
        return 1
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("croaster-webui: wrote src/webui_assets.h (%d files, %d bytes gzipped)" % (len(files), total))
    return 0


if __name__ == "__main__":
    sys.exit(run(check="--check" in sys.argv[1:]))
else:
    try:
        Import("env")  # noqa: F821 (SCons builtin): running as a PlatformIO extra script
        if run() != 0:
            env.Exit(1)  # noqa: F821
    except NameError:
        pass  # imported by the tests
